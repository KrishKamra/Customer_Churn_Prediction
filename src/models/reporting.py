"""Render machine- and human-readable benchmark reports from a tournament run."""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import TYPE_CHECKING, Any

from src.config import Settings

if TYPE_CHECKING:
    from src.models.train import ModelResult


def _fmt(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def _pm(mean: float, std: float) -> str:
    return f"{mean:.3f} ± {std:.3f}"


def benchmarks_payload(results: dict[str, ModelResult], metadata: dict[str, Any]) -> dict[str, Any]:
    return {
        "generated_at": metadata["trained_at"],
        "champion": metadata["champion"],
        "decision_threshold": metadata["decision_threshold"],
        "cost_matrix": metadata["cost_matrix"],
        "cv": {"folds": metadata["cv"]["folds"], "repeats": metadata["cv"]["repeats"]},
        "n_train": metadata["n_train"],
        "n_holdout": metadata["n_holdout"],
        "device": metadata["device"],
        "gpu": metadata["gpu"],
        "libraries": metadata["libraries"],
        "models": {k: asdict(r) for k, r in results.items()},
    }


def render_benchmarks_markdown(results: dict[str, ModelResult], metadata: dict[str, Any]) -> str:
    champion = metadata["champion"]
    cm = metadata["cost_matrix"]
    ranked = sorted(results.values(), key=lambda r: r.cv_mean["pr_auc"], reverse=True)
    n_hold = metadata["n_holdout"]

    lines = [
        "# Model Benchmarks",
        "",
        "> Auto-generated by `uv run python -m src.models.train` — do not edit by hand.  ",
        f"> Generated: `{metadata['trained_at']}` · Device: `{metadata['device']}`"
        + (f" (`{metadata['gpu']}`)" if metadata.get("gpu") else "")
        + f" · Champion: **{results[champion].display_name}**",
        "",
        "## Protocol",
        "",
        f"* **Data:** IBM Telco Customer Churn, {metadata['n_train']:,} training / "
        f"{n_hold:,} holdout customers (stratified, seed `{metadata['random_state']}`).",
        f"* **Validation:** Repeated Stratified {metadata['cv']['folds']}-Fold CV "
        f"× {metadata['cv']['repeats']} repeats on the training split. Every fold re-fits the "
        "full feature pipeline *and* isotonic calibration, so no information crosses folds.",
        "* **Selection:** highest mean CV PR-AUC (ties broken by lower expected cost).",
        f"* **Decision threshold:** minimises `{cm['fn']:g}×FN + {cm['fp']:g}×FP` on "
        "out-of-fold probabilities; the holdout is never used for any choice.",
        f"* **Dollar figures:** assume 1 cost unit = ${cm['unit_usd']:,.0f} "
        "(one wasted retention offer); a missed churner costs "
        f"{cm['fn']:g} units (${cm['fn'] * cm['unit_usd']:,.0f}). These are configurable "
        "assumptions (`CHURNAI_COST_*`), not measured values.",
        "",
        "## Cross-validated scorecard (training split)",
        "",
        "| Rank | Model | PR-AUC | ROC-AUC | Brier ↓ | Recall@0.5 | F2@0.5 | Cost / customer ↓ | Fit (s) |",
        "| ---: | :--- | :---: | :---: | :---: | :---: | :---: | :---: | ---: |",
    ]
    for i, r in enumerate(ranked, 1):
        name = f"**{r.display_name}** 🏆" if r.key == champion else r.display_name
        lines.append(
            f"| {i} | {name} | {_pm(r.cv_mean['pr_auc'], r.cv_std['pr_auc'])} | "
            f"{_pm(r.cv_mean['roc_auc'], r.cv_std['roc_auc'])} | "
            f"{_pm(r.cv_mean['brier'], r.cv_std['brier'])} | {_fmt(r.cv_mean['recall'])} | "
            f"{_fmt(r.cv_mean['f2'])} | {_fmt(r.cv_cost_per_customer)} | {r.fit_time_s:.1f} |"
        )

    lines += [
        "",
        "## Holdout scorecard (cost-optimal threshold per model)",
        "",
        "| Model | Threshold | ROC-AUC | PR-AUC | Recall | Precision | F2 | Brier ↓ | "
        "Latency (ms) | Expected loss ($) ↓ |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | ---: | ---: |",
    ]
    for r in sorted(results.values(), key=lambda r: r.holdout["expected_loss_usd"]):
        h = r.holdout
        name = f"**{r.display_name}** 🏆" if r.key == champion else r.display_name
        lines.append(
            f"| {name} | {r.oof_threshold:.2f} | {_fmt(h['roc_auc'])} | {_fmt(h['pr_auc'])} | "
            f"{_fmt(h['recall'])} | {_fmt(h['precision'])} | {_fmt(h['f2'])} | "
            f"{_fmt(h['brier'])} | {r.latency_ms:.1f} | {h['expected_loss_usd']:,.0f} |"
        )

    ch = results[champion].holdout
    naive_all = n_hold * (1 - metadata["train_churn_rate"]) * cm["fp"] * cm["unit_usd"]
    naive_none = n_hold * metadata["train_churn_rate"] * cm["fn"] * cm["unit_usd"]
    lines += [
        "",
        "## Cost analysis (champion, holdout)",
        "",
        "| Strategy | Expected loss ($) |",
        "| :--- | ---: |",
        f"| Do nothing (every churner missed) | {naive_none:,.0f} |",
        f"| Blanket offer to every customer | {naive_all:,.0f} |",
        f"| **ChurnAI champion @ {metadata['decision_threshold']:.2f}** | "
        f"**{ch['expected_loss_usd']:,.0f}** |",
        "",
        f"Confusion matrix at the deployed threshold: TP **{ch['tp']}**, FP **{ch['fp']}**, "
        f"TN **{ch['tn']}**, FN **{ch['fn']}**.",
        "",
        "## Reading these numbers",
        "",
        "* The non-leaky ceiling on this dataset is ROC-AUC ≈ 0.84–0.86; differences between "
        "the top contenders are typically inside one CV standard deviation, so simpler models "
        "are competitive and calibration matters as much as the algorithm.",
        "* *Recall@0.5 / F2@0.5* are reported for comparability only; production decisions use "
        "the cost-optimal threshold, which is far lower than 0.5 because a missed churner is "
        f"{cm['fn']:g}× more expensive than a wasted offer.",
        "* Latency is the median single-row `predict_proba` time on the training machine and "
        "includes the full feature pipeline.",
        "",
        "Machine-readable results: [`evaluations/model_benchmarks.json`]"
        "(evaluations/model_benchmarks.json). Curves: "
        "[`figures/roc_pr_curves.png`](figures/roc_pr_curves.png).",
        "",
    ]
    return "\n".join(lines)


def write_benchmark_reports(
    results: dict[str, ModelResult], metadata: dict[str, Any], settings: Settings
) -> None:
    settings.evaluations_dir.mkdir(parents=True, exist_ok=True)
    payload = benchmarks_payload(results, metadata)
    (settings.evaluations_dir / "model_benchmarks.json").write_text(
        json.dumps(payload, indent=2, default=str), encoding="utf-8"
    )
    (settings.docs_dir / "benchmarks.md").write_text(
        render_benchmarks_markdown(results, metadata), encoding="utf-8"
    )
